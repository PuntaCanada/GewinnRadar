test('Advent 2026 cannot silently double-count a source or promote unverified old-year material',()=>{
 const ids=[...data.confirmed,...data.review_candidates].map(x=>x.id);
 assert.equal(new Set(ids).size,ids.length,'calendar and pending candidate ids must be unique');
 assert.ok(data.confirmed.every(x=>/^https:\/\//.test(x.source_audit.evidence_url)));
 assert.ok(data.confirmed.every(x=>['2026-11-21','2026-11-22','2026-11-23'].includes(x.source_audit.checked_on)));
 assert.ok(data.confirmed.every(x=>!x.id.endsWith('2025')),'prior year cannot be counted as 2026');
 for(const x of data.review_candidates)assert.ok(!data.confirmed.some(y=>y.id===x.id),'unverified sources never counted as confirmed');
 assert.ok(data.review_candidates.some(x=>x.id==='holidaycheck-advent-2026'),'2025 page stays pending');
});

test('Berlin day respects midnight independently of browser timezone',()=>{
 assert.equal(berlinDay(at('2026-11-30T23:30:00Z')),'2026-12-01');
 assert.equal(berlinDay(at('2026-12-01T23:30:00Z')),'2026-12-02');
});
test('daily deadline only enforced when independently supported, never invented',()=>{
 const agravis=data.confirmed.find(g=>g.id==='agravis-advent-2026');
 const joska=data.confirmed.find(g=>g.id==='joska-advent-2026');
 const sz=data.confirmed.find(g=>g.id==='sz-advent-2026');
 const online=data.confirmed.find(g=>g.id==='t-online-advent-2026');
 const hair=data.confirmed.find(g=>g.id==='hairloft-loxstedt-advent-2026');
 assert.equal(dailyState(hair,at('2026-12-01T23:58:59+01:00')),'today');
 assert.equal(dailyState(hair,at('2026-12-01T23:59:00+01:00')),'deadline-passed');
 const pilot=data.confirmed.find(g=>g.id==='pilot-advent-2026');
 const draco=data.confirmed.find(g=>g.id==='draco-advent-2026');
 assert.equal(dailyState(pilot,at('2026-12-02T12:00:00+01:00')),'outside');
 assert.equal(dailyState(pilot,at('2026-12-03T12:00:00+01:00')),'today');
 assert.equal(dailyState(draco,at('2026-12-02T12:00:00+01:00')),'outside');
 assert.equal(dailyState(draco,at('2026-12-06T12:00:00+01:00')),'today');
 assert.equal(dailyState(joska,at('2026-12-01T07:59:00+01:00')),'not-open-yet');
 assert.equal(dailyState(joska,at('2026-12-01T08:00:00+01:00')),'today');
 assert.equal(dailyState(joska,at('2026-12-01T17:01:00+01:00')),'deadline-passed');
 assert.equal(dailyState(agravis,at('2026-12-03T23:59:00+01:00')),'today');
 assert.equal(dailyState(agravis,at('2026-12-03T23:59:30+01:00')),'today');
 assert.equal(dailyState(agravis,at('2026-12-04T00:00:00+01:00')),'today');
 assert.equal(dailyState(sz,at('2026-12-03T23:59:00+01:00')),'today');
 assert.equal(dailyState(online,at('2026-12-03T23:59:30+01:00')),'today','t-online cutoff not officially specified');
});
test('today marks are local, day-isolated, erasable, and cannot create arbitrary keys',()=>{
 const m=new Map(),store={getItem:k=>m.get(k)||null,setItem:(k,v)=>m.set(k,v),removeItem:k=>m.delete(k)};
 assert.equal(writeDayDone(store,'joska-advent-2026','2026-12-01',true),true);
 assert.equal(readDayDone(store,'joska-advent-2026','2026-12-01'),true);
 assert.equal(readDayDone(store,'joska-advent-2026','2026-12-02'),false);
 assert.equal(readDayDone(store,'agravis-advent-2026','2026-12-01'),false);
 assert.equal(writeDayDone(store,'../api/admin','2026-12-01',true),false);
 assert.equal(writeDayDone(store,'joska-advent-2026','2026-12-25',true),false);
 assert.equal(m.size,1);
 assert.equal(writeDayDone(store,'joska-advent-2026','2026-12-01',false),true);
 assert.equal(m.size,0);
});

test('hidden Advent calendars persist by stable ID, can be restored and reject invalid IDs',()=>{
 const m=new Map(),store={getItem:k=>m.get(k)||null,setItem:(k,v)=>m.set(k,v),removeItem:k=>m.delete(k)};
 const id='joska-advent-2026';
 assert.equal(readAdventHidden(store,id),false);
 assert.equal(writeAdventHidden(store,id,true),true);
 assert.equal(readAdventHidden(store,id),true);
 assert.equal(readAdventHidden(store,'agravis-advent-2026'),false);
 assert.equal(writeAdventHidden(store,'../api/admin',true),false);
 assert.equal(m.size,1);
 assert.equal(writeAdventHidden(store,id,false),true);
 assert.equal(readAdventHidden(store,id),false);
 assert.equal(m.size,0);
});
